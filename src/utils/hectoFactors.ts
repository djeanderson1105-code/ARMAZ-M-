/**
 * Returns the Hectoliter (HL) factor for a given product code
 */
export function getHectoFactor(productCode: string): number {
  const codeStr = String(productCode).trim();
  
  // Check the spreadsheet-based PRODUCT_DATABASE first for maximum accuracy
  const matchInDb = PRODUCT_DATABASE.find(p => p.codigo === codeStr);
  if (matchInDb) {
    return matchInDb.fatorHecto;
  }
  const matchInDbClean = PRODUCT_DATABASE.find(p => p.codigo === codeStr.replace(/^0+/, ""));
  if (matchInDbClean) {
    return matchInDbClean.fatorHecto;
  }

  if (PRODUCT_HECTO_FACTORS[codeStr] !== undefined) {
    return PRODUCT_HECTO_FACTORS[codeStr];
  }
  // Try fallback of removing leading/trailing zeros or spaces
  const cleanCode = codeStr.replace(/^0+/, "");
  if (PRODUCT_HECTO_FACTORS[cleanCode] !== undefined) {
    return PRODUCT_HECTO_FACTORS[cleanCode];
  }
  
  // Default fallback factor if code is unknown
  return 0.05;
}

/**
 * Calculates Hectoliters (HL) for a physical quantity of a product based on unit of measure (UM)
 */
export function calculateHL(productCode: string, quantity: number, um?: string, productDescription?: string): number {
  return calculateItemHL({
    codigo: productCode,
    quantidade: quantity,
    unidadeMedida: um,
    descricao: productDescription
  });
}

/**
 * Resolves Hectoliters (HL) for a record, dynamically ensuring unit of measure (UND vs CX) is properly applied.
 */
export function getRecordHL(r: { 
  produto?: string; 
  quantidade?: number; 
  um?: string; 
  unidadeMedida?: string; 
  hectolitros?: number;
  descricaoProduto?: string;
  descricao?: string;
}): number {
  const code = r.produto || "";
  const qty = Number(r.quantidade) || 0;
  if (qty <= 0) return 0;

  const um = (r.unidadeMedida || r.um || "").trim();
  const desc = r.descricaoProduto || r.descricao;

  return calculateHL(code, qty, um, desc);
}

/**
 * Checks if a record represents an approved request.
 */
export function isRecordApproved(r: { status?: string; statusPromax?: string }): boolean {
  const s = (r.status || "").toLowerCase().trim();
  const sp = (r.statusPromax || "").toLowerCase().trim();

  if (s.includes("reprov") || s.includes("cancela") || s.includes("pendent") || s.includes("recus") || s.includes("corrig")) {
    return false;
  }
  if (sp === "reprovado" || sp === "corrigir" || sp === "pendente") {
    return false;
  }

  if (s.includes("aprov") || s.includes("cadastrad") || s.includes("faturad") || s.includes("concluid") || s === "atendido" || sp === "cadastrado" || sp === "concluido") {
    return true;
  }

  return s !== "" && !s.includes("pend") && !s.includes("reprov") && !s.includes("cancela");
}

